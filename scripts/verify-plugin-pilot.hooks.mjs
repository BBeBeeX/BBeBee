/**
 * Node module customization hooks for `scripts/verify-plugin-pilot.mjs`
 * (registered there via `module.register`, which passes the mapping
 * tables in as `data` — see `initialize` below).
 *
 * These hooks simulate, inside a plain Node process, the two pieces of
 * module environment the desktop shell provides at runtime:
 *
 *  1. **The import map.** The host-shared bare specifiers (`react`,
 *     `react-dom`, `react-dom/client`, `react/jsx-runtime`,
 *     `react/jsx-dev-runtime`) resolve to the shell's host chunks
 *     (`apps/desktop/dist/host/*.js`) — exactly what the generated
 *     import map in `index.html` points them at. `react` itself goes
 *     through a one-line probe shim generated by the pilot script,
 *     which re-exports the host chunk unchanged and records the module
 *     namespace it received, so the pilot can assert object identity
 *     between the React the UI bundle saw and the host chunk's React.
 *     Every host-specifier resolution is appended to a JSONL log.
 *
 *  2. **The workspace platform modules.** A published plugin package's
 *     files keep bare imports of `cordis` / `@BBeBee/protocol` /
 *     `@BBeBee/toolkit` (the headless entry's established form); in the
 *     pilot's install directory there is no `node_modules`, so these
 *     resolve to the workspace's own builds — the same modules the
 *     shell's builtin copy of the plugin would use.
 *
 * One load-time shim: `dynamic-loader.ts` calls the vite-only
 * `import.meta.glob` API at module scope (to build the *builtin*
 * registry). The load hook rewrites that one token to a stub global
 * returning `{}`; `makeExternalEntry` / `composePluginWithUi` — the
 * functions under test — execute byte-identical.
 */
import { appendFileSync, existsSync, realpathSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'

let config = null

export function initialize(data) {
  config = data
}

const realUrl = (p) => pathToFileURL(realpathSync(p)).href

export async function resolve(specifier, context, nextResolve) {
  if (config && Object.hasOwn(config.hostTargets, specifier)) {
    const url = config.hostTargets[specifier]
    appendFileSync(
      config.resolutionLog,
      `${JSON.stringify({ specifier, parent: context.parentURL ?? null, url })}\n`,
    )
    return { url, shortCircuit: true }
  }
  if (config && Object.hasOwn(config.workspaceTargets, specifier)) {
    return { url: config.workspaceTargets[specifier], shortCircuit: true }
  }
  // Workspace sources import each other with build-style `.js`
  // specifiers that name `.ts`/`.tsx` files on disk (vite/tsc resolve
  // these; node's type stripping does not rewrite them). Only fires
  // when the literal `.js` file does not exist.
  if (
    (specifier.startsWith('./') || specifier.startsWith('../')) &&
    specifier.endsWith('.js') &&
    context.parentURL?.startsWith('file:')
  ) {
    const target = fileURLToPath(new URL(specifier, context.parentURL))
    if (!existsSync(target)) {
      for (const cand of [`${target.slice(0, -3)}.ts`, `${target.slice(0, -3)}.tsx`]) {
        if (existsSync(cand)) return { url: realUrl(cand), shortCircuit: true }
      }
    }
  }
  return nextResolve(specifier, context)
}

export async function load(url, context, nextLoad) {
  if (config && url === config.dynamicLoaderUrl) {
    const result = await nextLoad(url, context)
    const text =
      typeof result.source === 'string'
        ? result.source
        : result.source instanceof Uint8Array
          ? new TextDecoder().decode(result.source)
          : null
    if (text?.includes('import.meta.glob')) {
      return {
        ...result,
        source: text.replaceAll('import.meta.glob', 'globalThis.__bbebeeGlobStub'),
      }
    }
    return result
  }
  return nextLoad(url, context)
}
