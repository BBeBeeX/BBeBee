//! Desktop Taskbar and Thumbnail Toolbar controls.
//!
//! Provides synchronized controls for:
//! - System tray menu across platforms.
//! - Windows Taskbar Thumbnail Toolbar (`ITaskbarList3::ThumbBarAddButtons` / `ThumbBarUpdateButtons`)
//!   supporting `Previous`, `Play/Pause`, `Next`, and `Favorite/Unfavorite`.

use crate::state::AppState;

/// Synchronizes playback state across tray menu and desktop taskbar.
pub fn update_taskbar(app: &tauri::AppHandle, state: &AppState) -> Result<(), String> {
    // 1. Cross-platform Tray menu update
    let _ = crate::tray::update_tray_menu(app, state);

    // 2. Windows Taskbar Thumbnail Toolbar
    #[cfg(target_os = "windows")]
    {
        let _ = windows_taskbar::update_thumbbar_buttons(app, state);
    }

    Ok(())
}

