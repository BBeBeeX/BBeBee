    struct TaskbarIcons {
        prev: HICON,
        play: HICON,
        pause: HICON,
        next: HICON,
        favorite: HICON,
        unfavorite: HICON,
    }

    unsafe impl Send for TaskbarIcons {}
    unsafe impl Sync for TaskbarIcons {}

    impl Drop for TaskbarIcons {
        fn drop(&mut self) {
            unsafe {
                let _ = DestroyIcon(self.prev);
                let _ = DestroyIcon(self.play);
                let _ = DestroyIcon(self.pause);
                let _ = DestroyIcon(self.next);
                let _ = DestroyIcon(self.favorite);
                let _ = DestroyIcon(self.unfavorite);
            }
        }
    }

    unsafe fn create_icon(bytes: &[u8]) -> Option<HICON> {
        CreateIconFromResourceEx(
            bytes,
            true,
            0x00030000,
            16,
            16,
            IMAGE_FLAGS(0),
        ).ok()
    }

    fn get_taskbar_icons() -> Option<&'static TaskbarIcons> {
        static ICONS: OnceLock<TaskbarIcons> = OnceLock::new();
        ICONS.get_or_init(|| unsafe {
            TaskbarIcons {
                prev: create_icon(PREV_PNG).unwrap_or(HICON(core::ptr::null_mut())),
                play: create_icon(PLAY_PNG).unwrap_or(HICON(core::ptr::null_mut())),
                pause: create_icon(PAUSE_PNG).unwrap_or(HICON(core::ptr::null_mut())),
                next: create_icon(NEXT_PNG).unwrap_or(HICON(core::ptr::null_mut())),
                favorite: create_icon(FAVORITE_PNG).unwrap_or(HICON(core::ptr::null_mut())),
                unfavorite: create_icon(UNFAVORITE_PNG).unwrap_or(HICON(core::ptr::null_mut())),
            }
        });
        ICONS.get()
    }

    fn to_wide_tip(s: &str) -> [u16; 260] {
        let mut tip = [0u16; 260];
        let wide: Vec<u16> = s.encode_utf16().collect();
        let len = wide.len().min(259);
        tip[..len].copy_from_slice(&wide[..len]);
        tip
    }

    unsafe extern "system" fn taskbar_subclass_proc(
        hwnd: HWND,
        msg: u32,
        wparam: WPARAM,
        lparam: LPARAM,
        _uid_subclass: usize,
        _ref_data: usize,
    ) -> LRESULT {
        if msg == WM_COMMAND {
            let hi = ((wparam.0 >> 16) & 0xFFFF) as u32;
            let lo = (wparam.0 & 0xFFFF) as u32;
            if hi == THBN_CLICKED {
                if let Some(app) = APP_HANDLE.get() {
                    match lo {
                        BUTTON_PREV => crate::tray::emit_to_main(app, "taskbar:action", "previous"),
                        BUTTON_PLAY_PAUSE => crate::tray::emit_to_main(app, "taskbar:action", "togglePlay"),
                        BUTTON_NEXT => crate::tray::emit_to_main(app, "taskbar:action", "next"),
                        BUTTON_FAVORITE => crate::tray::emit_to_main(app, "taskbar:action", "toggleFavorite"),
                        _ => {}
                    }
                    return LRESULT(0);
                }
            }
        }
        DefSubclassProc(hwnd, msg, wparam, lparam)
    }

    pub fn update_thumbbar_buttons(app: &tauri::AppHandle, state: &AppState) -> Result<(), String> {
        let Some(win) = app.get_webview_window("main") else {
            return Ok(());
        };
        let is_visible = win.is_visible().unwrap_or(false);
        if !is_visible {
            return Ok(());
        }

        let hwnd_raw = win.hwnd().map_err(|e| e.to_string())?;
        let hwnd = HWND(hwnd_raw.0 as *mut _);

        let icons = match get_taskbar_icons() {
            Some(i) => i,
            None => return Err("Failed to create taskbar icons".to_string()),
        };

        let taskbar = lock_recover(&state.taskbar_state).clone();
        let i18n = get_tray_i18n(&state.get_locale());

        let mut buttons: [THUMBBUTTON; 4] = unsafe { core::mem::zeroed() };

        // 1. Prev Button
        buttons[0].dwMask = THB_FLAGS | THB_ICON | THB_TOOLTIP;
        buttons[0].iId = BUTTON_PREV;
        buttons[0].hIcon = icons.prev;
        buttons[0].szTip = to_wide_tip(i18n.prev);
        buttons[0].dwFlags = if taskbar.can_previous.unwrap_or(true) {
            THBF_ENABLED
        } else {
            THBF_DISABLED
        };

        // 2. Play / Pause Button
        buttons[1].dwMask = THB_FLAGS | THB_ICON | THB_TOOLTIP;
        buttons[1].iId = BUTTON_PLAY_PAUSE;
        if taskbar.is_playing {
            buttons[1].hIcon = icons.pause;
            buttons[1].szTip = to_wide_tip(i18n.pause);
        } else {
            buttons[1].hIcon = icons.play;
            buttons[1].szTip = to_wide_tip(i18n.play);
        }
        buttons[1].dwFlags = if taskbar.can_play_or_pause.unwrap_or(true) {
            THBF_ENABLED
        } else {
            THBF_DISABLED
        };

        // 3. Next Button
        buttons[2].dwMask = THB_FLAGS | THB_ICON | THB_TOOLTIP;
        buttons[2].iId = BUTTON_NEXT;
        buttons[2].hIcon = icons.next;
        buttons[2].szTip = to_wide_tip(i18n.next);
        buttons[2].dwFlags = if taskbar.can_next.unwrap_or(true) {
            THBF_ENABLED
        } else {
            THBF_DISABLED
        };

        // 4. Favorite / Unfavorite Button
        buttons[3].dwMask = THB_FLAGS | THB_ICON | THB_TOOLTIP;
        buttons[3].iId = BUTTON_FAVORITE;
        if taskbar.is_favorite.unwrap_or(false) {
            buttons[3].hIcon = icons.favorite;
            buttons[3].szTip = to_wide_tip(i18n.unfavorite);
        } else {
            buttons[3].hIcon = icons.unfavorite;
            buttons[3].szTip = to_wide_tip(i18n.favorite);
        }
        buttons[3].dwFlags = if taskbar.can_favorite.unwrap_or(false) || taskbar.title.is_some() {
            THBF_ENABLED
        } else {
            THBF_DISABLED
        };

        unsafe {
            let taskbar_list: ITaskbarList3 = CoCreateInstance(&TaskbarList, None, CLSCTX_INPROC_SERVER)
                .map_err(|e| format!("CoCreateInstance TaskbarList failed: {e}"))?;

            let _ = taskbar_list.HrInit();

            let _ = APP_HANDLE.set(app.clone());

            if !THUMBBAR_INITIALIZED.load(Ordering::SeqCst) {
                let res = taskbar_list.ThumbBarAddButtons(hwnd, &buttons);
                if res.is_ok() {
                    THUMBBAR_INITIALIZED.store(true, Ordering::SeqCst);
                    let _ = SetWindowSubclass(hwnd, Some(taskbar_subclass_proc), SUBCLASS_ID, 0);
                } else {
                    return Err(format!("ThumbBarAddButtons failed: {:?}", res));
                }
            } else {
                let res = taskbar_list.ThumbBarUpdateButtons(hwnd, &buttons);
                if res.is_err() {
                    // If window was recreated or lost, try re-adding
                    let add_res = taskbar_list.ThumbBarAddButtons(hwnd, &buttons);
                    if add_res.is_ok() {
                        let _ = SetWindowSubclass(hwnd, Some(taskbar_subclass_proc), SUBCLASS_ID, 0);
                    }
                }
            }
        }

        Ok(())
    }
